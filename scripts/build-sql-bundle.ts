/**
 * Builds the Supabase SQL Editor bundle in supabase/sql/ from:
 *   - the Drizzle migrations in ./drizzle (byte-for-byte), plus the matching rows in
 *     drizzle.__drizzle_migrations so `npm run db:migrate` later sees them as applied;
 *   - the fictional seed data, produced by running scripts/seed.ts against a throwaway
 *     LOCAL database and exporting it with pg_dump.
 *
 *   SEED_SOURCE_DATABASE_URL=postgres://…@localhost:5432/caps_bundle npx tsx scripts/build-sql-bundle.ts
 *
 * The source database must be local and empty-but-migrated; it is never a Supabase database.
 */
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const OUT = "supabase/sql";
const src = process.env.SEED_SOURCE_DATABASE_URL;
if (!src || !/@(localhost|127\.0\.0\.1)[:/]/.test(src)) throw new Error("SEED_SOURCE_DATABASE_URL must be a local database");
fs.mkdirSync(OUT, { recursive: true });

const journal = JSON.parse(fs.readFileSync("drizzle/meta/_journal.json", "utf8")) as { entries: { tag: string; when: number }[] };
const header = (title: string, body: string) =>
  `-- =============================================================================\n-- CAPS · ${title}\n-- Generated by scripts/build-sql-bundle.ts — do not edit by hand.\n${body
    .split("\n")
    .map((l) => `-- ${l}`.trimEnd())
    .join("\n")}\n-- =============================================================================\n\n`;

/* ------------------------------------------------------------------ 00 preflight (read-only) */
fs.writeFileSync(
  path.join(OUT, "00_preflight.sql"),
  header("Step 1 — PREFLIGHT (read-only)", "Confirms which database you are connected to and that it is empty.\nChanges nothing. Run it, then share the single result row.") +
    `select
  current_database()                                                   as database,
  current_user                                                         as connected_as,
  split_part(version(), ' ', 2)                                        as postgres_version,
  (select count(*) from pg_tables where schemaname = 'public')          as public_tables,
  (select string_agg(tablename, ', ' order by tablename) from pg_tables where schemaname = 'public') as existing_public_tables,
  to_regclass('drizzle.__drizzle_migrations') is not null              as caps_migrations_present,
  exists (select 1 from pg_roles where rolname = 'anon')
    and exists (select 1 from pg_roles where rolname = 'authenticated') as supabase_api_roles_present,
  now()                                                                as checked_at;
`,
);

/* ------------------------------------------------------------------ 01 schema */
let schema = header(
  "Step 2 — SCHEMA, SECURITY & REFERENCE DATA",
  "Creates all CAPS tables, constraints and indexes, enables Row Level Security,\nmakes audit_logs append-only, and inserts roles, permissions and default\ngroup-to-role mappings. Records the migrations for `npm run db:migrate`.\nRuns in one transaction and refuses to run if CAPS tables already exist.",
);
schema += `begin;

do $$
begin
  if to_regclass('public.users') is not null or to_regclass('drizzle.__drizzle_migrations') is not null then
    raise exception 'CAPS schema already present in this database — aborting without changes.';
  end if;
end $$;

`;
const rows: string[] = [];
for (const e of journal.entries) {
  const sql = fs.readFileSync(`drizzle/${e.tag}.sql`, "utf8");
  const hash = createHash("sha256").update(sql).digest("hex");
  schema += `-- ---------------------------------------------------------------- migration ${e.tag}\n${sql.replace(/--> statement-breakpoint/g, "")}\n\n`;
  rows.push(`  ('${hash}', ${e.when})`);
}
schema += `-- ---------------------------------------------------------------- migration bookkeeping (Drizzle)
create schema if not exists drizzle;
create table if not exists drizzle.__drizzle_migrations (
  id serial primary key,
  hash text not null,
  created_at bigint
);
insert into drizzle.__drizzle_migrations (hash, created_at) values
${rows.join(",\n")};

commit;

select 'CAPS schema installed' as result,
       (select count(*) from pg_tables where schemaname = 'public') as public_tables,
       (select count(*) from public.application_roles) as roles,
       (select count(*) from public.role_mappings) as role_mappings,
       (select count(*) from drizzle.__drizzle_migrations) as migrations_recorded;
`;
fs.writeFileSync(path.join(OUT, "01_schema.sql"), schema);

/* ------------------------------------------------------------------ 02 seed */
const tables = ["users", "groups", "institutions", "programmes", "applicants", "admission_applications", "admission_reviews", "admission_decisions", "audit_logs"];
const dump = execFileSync(
  "pg_dump",
  ["--data-only", "--column-inserts", "--rows-per-insert=50", "--no-owner", "--no-privileges", ...tables.flatMap((t) => ["--table", `public.${t}`]), src],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
);
const body = dump
  .split("\n")
  // Keep the INSERT statements only: drop session SETs, set_config calls, psql meta-commands (\restrict…) and comments.
  .filter((l) => !/^(SET |SELECT pg_catalog\.|\\|--)/.test(l))
  .join("\n")
  .replace(/\n{3,}/g, "\n\n")
  .trim();
if (!body.includes("INSERT INTO public.applicants")) throw new Error("Seed export looks empty — run migrations and the seed on the source database first.");
if (/@(?!sample\.caps-demo\.ng)[a-z0-9.-]+\.[a-z]{2,}/i.test(body.replace(/'[^']*@sample\.caps-demo\.ng'/g, ""))) {
  // Defence in depth: the seed must only contain fictional @sample.caps-demo.ng addresses.
  throw new Error("Seed export contains an e-mail address outside @sample.caps-demo.ng — aborting.");
}
const seed =
  header(
    "Step 3 — FICTIONAL DEMONSTRATION DATA",
    "Fictional institutions, programmes, applicants and admission records, sample staff\n(@sample.caps-demo.ng, cannot sign in) and pre-existing CAPS groups for Fixiam import.\nNo Fixiam-provisioned users are created. Runs in one transaction and refuses to run\nif sample data already exists.",
  ) +
  `begin;

do $$
begin
  if to_regclass('public.applicants') is null then
    raise exception 'Run 01_schema.sql first.';
  end if;
  if exists (select 1 from public.applicants) or exists (select 1 from public.groups) then
    raise exception 'Sample data already present — aborting without changes.';
  end if;
end $$;

${body}

select setval('public.audit_logs_id_seq', (select coalesce(max(id), 1) from public.audit_logs));

commit;

select 'CAPS sample data loaded' as result,
       (select count(*) from public.institutions) as institutions,
       (select count(*) from public.applicants) as applicants,
       (select count(*) from public.users where provisioning_source = 'sample') as sample_staff,
       (select count(*) from public.groups) as groups;
`;
fs.writeFileSync(path.join(OUT, "02_seed.sql"), seed);

/* ------------------------------------------------------------------ 03 verify (read-only) */
fs.writeFileSync(
  path.join(OUT, "03_verify.sql"),
  header("Step 4 — VERIFY (read-only)", "Equivalent of `npm run db:check`. Changes nothing. Share the single result row.") +
    `select
  (select count(*) from drizzle.__drizzle_migrations)                                    as migrations_recorded,
  (select count(*) from pg_tables where schemaname = 'public')                           as public_tables,
  (select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace
     where n.nspname = 'public' and c.relkind = 'r' and not c.relrowsecurity)             as tables_without_rls,
  (select count(*) from information_schema.role_table_grants
     where table_schema = 'public' and grantee in ('anon', 'authenticated'))             as api_role_grants,
  exists (select 1 from pg_trigger where tgname = 'audit_logs_no_update')                as audit_log_append_only,
  (select count(*) from public.application_roles)                                        as roles,
  (select count(*) from public.permissions)                                              as permissions,
  (select count(*) from public.role_mappings where enabled)                              as enabled_role_mappings,
  (select count(*) from public.institutions)                                             as institutions,
  (select count(*) from public.applicants)                                               as applicants,
  (select string_agg(display_name, ', ' order by display_name) from public.groups)       as groups,
  (select count(*) from public.users where provisioning_source = 'sample')               as sample_staff,
  (select count(*) from public.users where provisioning_source = 'scim')                 as fixiam_provisioned_users;
`,
);

for (const f of fs.readdirSync(OUT).sort()) console.log(`${f}  ${fs.statSync(path.join(OUT, f)).size.toLocaleString()} bytes`);
